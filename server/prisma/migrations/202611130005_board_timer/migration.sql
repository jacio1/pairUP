CREATE TABLE "RoomTimer" (
 "roomId" TEXT PRIMARY KEY REFERENCES "Room"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "mode" TEXT NOT NULL DEFAULT 'focus', "focusSeconds" INTEGER NOT NULL DEFAULT 1500,
 "breakSeconds" INTEGER NOT NULL DEFAULT 300, "longBreakSeconds" INTEGER NOT NULL DEFAULT 900,
 "remainingMs" INTEGER NOT NULL DEFAULT 1500000, "endsAt" TIMESTAMP(3),
 "completed" INTEGER NOT NULL DEFAULT 0, "version" INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE "RoomBoard" (
 "roomId" TEXT PRIMARY KEY REFERENCES "Room"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "generation" INTEGER NOT NULL DEFAULT 0, "version" INTEGER NOT NULL DEFAULT 0,
 "elements" JSONB NOT NULL DEFAULT '[]'
);
